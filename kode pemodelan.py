    print(
        f"Memproses sektor {sektor_target} | "
        f"{skenario} | {metode}"
    )

    # ========================================================
    # 3. AMBIL MODEL SVR S7
    # ========================================================

    if key not in trained_models_svr:
        raise KeyError(
            f"Model {key} tidak ditemukan di trained_models_svr."
        )

    hasil_model = trained_models_svr[key]

    model = hasil_model['model']
    scaler = hasil_model['scaler']
    fitur = hasil_model['fitur']

    # ========================================================
    # 4. SIAPKAN DATA TEST S7
    # ========================================================

    X_test_raw = X_S7_test[sektor_target].copy()

    # Samakan fitur dan urutannya dengan saat training
    X_test_raw = X_test_raw[fitur]

    # ========================================================
    # 5. TARGET TEST
    # ========================================================

    y_test = Y_test[sektor_target]

    # Pastikan jumlah observasi sesuai
    if len(X_test_raw) != len(y_test):
        raise ValueError(
            f"Jumlah observasi X dan y tidak sama "
            f"untuk sektor {sektor_target}."
        )

    # ========================================================
    # 6. STANDARDISASI DATA TEST
    # Gunakan scaler yang sudah fit pada data training
    # ========================================================

    X_test_scaled = scaler.transform(X_test_raw)

    # ========================================================
    # 7. PERMUTATION IMPORTANCE
    # ========================================================

    perm_result = permutation_importance(
        estimator=model,
        X=X_test_scaled,
        y=y_test,
        scoring='neg_root_mean_squared_error',
        n_repeats=30,
        random_state=42,
        n_jobs=-1
    )

    importance_mean = perm_result.importances_mean
    importance_std = perm_result.importances_std

    # ========================================================
    # 8. SIMPAN HASIL
    # ========================================================

    for nama_fitur, imp, std in zip(
        fitur,
        importance_mean,
        importance_std
    ):

        feature_importance_results.append({
            'Sektor Target': sektor_target,
            'Skenario': skenario,
            'Metode': metode,
            'Variabel': nama_fitur,
            'Importance': imp,
            'Std Importance': std
        })


